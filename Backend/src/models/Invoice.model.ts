// models/Invoice.model.ts
import mongoose, { Document, Schema } from 'mongoose';
import { nextYearlyId } from '../utils/sequence';

export const INVOICE_CURRENCIES = ['USD', 'INR', 'NPR'] as const;
export const PAYMENT_TYPES = ['Full payment', 'Advance payment', 'Partial payment', 'Final payment'] as const;

export interface IInvoiceItem {
  description: string;
  quantity: number;
  unitPrice: number;
}

// Every payment recorded against an invoice is one receipt.
export interface IPayment {
  _id: mongoose.Types.ObjectId;
  receiptNumber: string;
  date: Date;
  amount: number;
  paidBy: string;
  method: string;
  transactionId?: string;
  paymentType: (typeof PAYMENT_TYPES)[number];
  note?: string;
  createdAt: Date;
}

export interface IInvoice extends Document {
  invoiceNumber: string;
  booking?: mongoose.Types.ObjectId;
  bookingRef?: string;
  issueDate: Date;
  dueDate?: Date;
  currency: (typeof INVOICE_CURRENCIES)[number];
  client: {
    name: string;
    address?: string;
    country?: string;
    nationality?: string;
    phone?: string;
    email?: string;
  };
  packageName?: string;
  travelDate?: string;
  travellers?: number;
  items: IInvoiceItem[];
  discount: number;
  taxPercent: number;
  notes?: string;
  status: 'Issued' | 'Cancelled';
  subtotal: number;
  taxAmount: number;
  total: number;
  payments: mongoose.Types.DocumentArray<IPayment & mongoose.Types.Subdocument>;
  // Virtuals
  amountPaid: number;
  balance: number;
  paymentStatus: 'Unpaid' | 'Partially paid' | 'Paid';
  createdAt: Date;
  updatedAt: Date;
}

const round2 = (n: number) => Math.round(n * 100) / 100;

const itemSchema = new Schema<IInvoiceItem>(
  {
    description: { type: String, required: [true, 'Item description is required'], trim: true },
    quantity: { type: Number, required: true, min: [0, 'Quantity cannot be negative'], default: 1 },
    unitPrice: { type: Number, required: true, min: [0, 'Price cannot be negative'], default: 0 },
  },
  { _id: false }
);

const paymentSchema = new Schema<IPayment>(
  {
    // Generated by the invoice pre-save hook below (validation runs before it).
    receiptNumber: { type: String },
    date: { type: Date, required: [true, 'Payment date is required'] },
    amount: { type: Number, required: [true, 'Amount is required'], min: [0.01, 'Amount must be more than 0'] },
    paidBy: { type: String, required: [true, 'Paid by is required'], trim: true },
    method: { type: String, required: [true, 'Payment method is required'], trim: true },
    transactionId: { type: String, trim: true },
    paymentType: { type: String, enum: PAYMENT_TYPES, default: 'Full payment' },
    note: { type: String, trim: true },
  },
  { timestamps: { createdAt: true, updatedAt: false } }
);

const invoiceSchema = new Schema<IInvoice>(
  {
    invoiceNumber: { type: String, unique: true },
    booking: { type: Schema.Types.ObjectId, ref: 'Booking' },
    bookingRef: { type: String, trim: true },
    issueDate: { type: Date, required: true, default: Date.now },
    dueDate: { type: Date },
    currency: { type: String, enum: INVOICE_CURRENCIES, default: 'USD' },
    client: {
      name: { type: String, required: [true, 'Client name is required'], trim: true },
      address: { type: String, trim: true },
      country: { type: String, trim: true },
      nationality: { type: String, trim: true },
      phone: { type: String, trim: true },
      email: { type: String, trim: true, lowercase: true },
    },
    packageName: { type: String, trim: true },
    travelDate: { type: String, trim: true },
    travellers: { type: Number, min: 0 },
    items: {
      type: [itemSchema],
      validate: [(items: IInvoiceItem[]) => items.length > 0, 'Add at least one item'],
    },
    discount: { type: Number, default: 0, min: 0 },
    taxPercent: { type: Number, default: 0, min: 0, max: 100 },
    notes: { type: String, trim: true },
    status: { type: String, enum: ['Issued', 'Cancelled'], default: 'Issued' },
    subtotal: { type: Number, default: 0 },
    taxAmount: { type: Number, default: 0 },
    total: { type: Number, default: 0 },
    payments: { type: [paymentSchema], default: [] },
  },
  {
    timestamps: true,
    toJSON: { virtuals: true },
    toObject: { virtuals: true },
  }
);

invoiceSchema.index({ createdAt: -1 });
invoiceSchema.index({ booking: 1 });
invoiceSchema.index({ 'payments.receiptNumber': 1 });

invoiceSchema.virtual('amountPaid').get(function (this: IInvoice) {
  return round2((this.payments || []).reduce((sum, p) => sum + p.amount, 0));
});

invoiceSchema.virtual('balance').get(function (this: IInvoice) {
  return round2(this.total - this.amountPaid);
});

invoiceSchema.virtual('paymentStatus').get(function (this: IInvoice) {
  if (this.amountPaid <= 0) return 'Unpaid';
  return this.balance <= 0 ? 'Paid' : 'Partially paid';
});

// Totals are always worked out here so the PDF and the list can never disagree.
invoiceSchema.pre('validate', function (next) {
  const subtotal = round2(this.items.reduce((sum, item) => sum + item.quantity * item.unitPrice, 0));
  const taxable = Math.max(0, subtotal - (this.discount || 0));
  this.subtotal = subtotal;
  this.taxAmount = round2((taxable * (this.taxPercent || 0)) / 100);
  this.total = round2(taxable + this.taxAmount);
  next();
});

invoiceSchema.pre('save', async function (next) {
  try {
    const Invoice = mongoose.model('Invoice');
    if (!this.invoiceNumber) {
      this.invoiceNumber = await nextYearlyId(
        'Invoice.invoiceNumber',
        'INV',
        (id) => Invoice.exists({ invoiceNumber: id }),
        new Date(this.issueDate).getFullYear()
      );
    }
    for (const payment of this.payments) {
      if (!payment.receiptNumber) {
        payment.receiptNumber = await nextYearlyId(
          'Invoice.receiptNumber',
          'RCT',
          (id) => Invoice.exists({ 'payments.receiptNumber': id }),
          new Date(payment.date).getFullYear()
        );
      }
    }
    next();
  } catch (error) {
    next(error as Error);
  }
});

const Invoice = mongoose.model<IInvoice>('Invoice', invoiceSchema);

export default Invoice;
